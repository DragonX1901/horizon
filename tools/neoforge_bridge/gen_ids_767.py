#!/usr/bin/env python3
"""Generate crates/horizon-neoforge-bridge/src/ids_767.rs from the 1.21.1 data
generator's packets report (`java -DbundlerMainClass=net.minecraft.data.Main
-jar server.jar --reports` on the 1.21.1 server jar).

Packet ids are protocol facts: the order packets are registered in each
connection state. The report is the authoritative source for them.
"""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STATES = ["handshake", "status", "login", "configuration", "play"]
DIRECTIONS = ["clientbound", "serverbound"]


def const_name(name):
    return name.split(":", 1)[1].replace("/", "_").upper()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=ROOT / "crates/horizon-neoforge-bridge/src/ids_767.rs")
    args = parser.parse_args()
    report = json.loads(args.report.read_text())
    lines = [
        "//! Packet ids per connection state and direction for protocol 767 (1.21.1).",
        "//! Generated by tools/neoforge_bridge/gen_ids_767.py from the 1.21.1 data",
        "//! generator's packets report; do not edit by hand.",
        "#![allow(missing_docs, dead_code)]",
        "",
    ]
    for state in STATES:
        lines.append(f"pub mod {state} {{")
        for direction in DIRECTIONS:
            packets = report.get(state, {}).get(direction, {})
            if not packets:
                continue
            ordered = sorted(packets.items(), key=lambda kv: kv[1]["protocol_id"])
            assert [e["protocol_id"] for _, e in ordered] == list(range(len(ordered))), (state, direction)
            lines.append(f"    pub mod {direction} {{")
            for name, entry in ordered:
                lines.append(f"        pub const {const_name(name)}: i32 = {entry['protocol_id']};")
            lines.append("        /// Packet names indexed by id.")
            lines.append("        pub const NAMES: &[&str] = &[")
            for name, _ in ordered:
                lines.append(f'            "{name.split(":", 1)[1]}",')
            lines.append("        ];")
            lines.append("    }")
        lines.append("}")
    args.out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
